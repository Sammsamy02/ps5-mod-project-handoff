#!/usr/bin/env python3
"""build_selftest.py — worker-payload-selftest, 2026-10-05.

Receipted ONE-DISPATCH build of the batched standalone payload self-test:
  * host build (macOS, /usr/bin/clang++, HOST_SELFTEST defined — the on-target
    garble assertion 1a is compiled out; 1b widen-loop correctness verified);
  * prospero build (ps5-payload-sdk prospero-clang++, x86_64-sie-ps5, SDK
    prebuilt libc++ — the 1a garble assertion compiled in), linked standalone
    ELF on the proven /loadpayload link class (-Wl,--build-id=none per the
    argv-probe determinism finding).

Every command is receipted (argv + exit code + log file). Build ids are the
first 12 hex chars of each built binary's sha256; results collected from a
binary are tagged with that binary's build id.

Bounded retries: at most TWO retries of a FAILED build step (fresh log per
attempt, never a replay of an already-succeeded step), then stop and report.

Writes only inside this worker directory (plus /tmp scratch for nothing).
No console contact here; dispatch is a separate bounded step.
"""
from pathlib import Path
import hashlib
import json
import subprocess
import sys
import time

WORKER = Path(__file__).resolve().parent
WS = WORKER.parents[2]  # outputs/2026-10-04-zcode-team/../.. -> worktree root
TEAM = WORKER.parent

SDK = WS / "outputs/ps5-mod-bridge/native-host/build/sdk-v0.43/ps5-payload-sdk"
LLVM_CONFIG = WS / "outputs/ps5-mod-bridge/native-probe/build/deps/llvm/LLVM-21.1.8-macOS-ARM64/bin/llvm-config"
LINEAGE_INCLUDE = TEAM / "worker-launch11-vtable-prebuild/staging/lineage-overlay-2-l11-b"
SOURCE_IMPL = WS / ".superpowers/native-dependency-spike/native-coherent-runtime-1/source-generations/composition-1/port/ue4ss/src/Platform/NativeModSource.cpp"
BUNDLE_MAIN_LUA = TEAM / "worker-itemspawner-bundle/bundle/ue4ss/Mods/TownfallItemSpawner/Scripts/main.lua"
EXPECT_MAIN_LUA_BYTES = 21415
EXPECT_MAIN_LUA_SHA = "f586043a1ca5708113e8ee31532d6396cbb0866daeae473722dd8880b6559658"
PARSER_HEADER_SHA = "b12a5ac5aebbc2635995657cdd4aed14314a9c3dfdba30c284a3ae2fb1f64a15"
SEED_VALIDATION_SHA = "db07ac602cd9e57aeb864780874aa7e9b16158d25aefdc200c32ffd564871f83"
LLVM_BIN = LLVM_CONFIG.parent

MAX_BUILD_RETRIES = 2  # bounded: two retries per failed step, then stop

records = []


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def run(name, argv, env=None, timeout=240):
    """Run one receipted command; on failure retry up to MAX_BUILD_RETRIES
    with a distinct attempt log; never replay a succeeded step."""
    logs = WORKER / "logs"
    logs.mkdir(exist_ok=True)
    attempts = []
    for attempt in range(1 + MAX_BUILD_RETRIES):
        log = logs / f"{name}.attempt{attempt + 1}.log"
        started = time.time()
        proc = subprocess.run([str(a) for a in argv], cwd=str(WORKER), env=env,
                              capture_output=True, text=True, timeout=timeout)
        log.write_text(proc.stdout + proc.stderr)
        attempts.append({"attempt": attempt + 1, "log": str(log.relative_to(WORKER)),
                         "exit_code": proc.returncode, "seconds": round(time.time() - started, 2)})
        records.append({"name": f"{name}.attempt{attempt + 1}",
                        "argv": [str(a) for a in argv],
                        "exit_code": proc.returncode, "log": str(log)})
        if proc.returncode == 0:
            return attempts
        print(f"{name} attempt {attempt + 1} FAILED (rc={proc.returncode}), log={log}",
              file=sys.stderr)
    raise SystemExit(f"BUILD FAILED after {1 + MAX_BUILD_RETRIES} bounded attempts: {name}")


def generate_bytes_header():
    data = BUNDLE_MAIN_LUA.read_bytes()
    digest = sha256(BUNDLE_MAIN_LUA)
    if len(data) != EXPECT_MAIN_LUA_BYTES or digest != EXPECT_MAIN_LUA_SHA:
        raise SystemExit(f"REFUSED: bundle main.lua identity drifted: "
                         f"{len(data)} bytes sha {digest}")
    lines = [f"// generated by build_selftest.py from {BUNDLE_MAIN_LUA}",
             f"// sha256 {digest}, {len(data)} bytes — byte-exact embed",
             "#pragma once",
             "#include <cstddef>",
             "static const unsigned char kMainLuaBytes[] = {"]
    for i in range(0, len(data), 20):
        lines.append(",".join(str(b) for b in data[i:i + 20]) + ",")
    lines.append("};")
    lines.append(f"static const size_t kMainLuaBytesLen = sizeof(kMainLuaBytes);")
    lines.append(f'static const char kMainLuaSha256[] = "{digest}";')
    header = WORKER / "src/main_lua_bytes.hpp"
    header.write_text("\n".join(lines) + "\n")
    records.append({"name": "generate_main_lua_bytes", "exit_code": 0,
                    "output": str(header), "sha256": digest, "bytes": len(data)})
    print(f"main_lua_bytes.hpp generated: {len(data)} bytes sha {digest[:12]}")


COMMON = ["-std=c++20", "-O1", "-Wall", "-Wextra",
          "-Wno-deprecated-declarations",
          "-I", WORKER / "src",
          "-I", LINEAGE_INCLUDE]


def build_host():
    out = WORKER / "host/payload_selftest-host"
    run("host-build", ["/usr/bin/clang++", *COMMON, "-DHOST_SELFTEST",
                       WORKER / "src/payload_selftest.cpp", SOURCE_IMPL, "-o", out])
    return out


def build_prospero():
    out = WORKER / "build/payload_selftest.elf"
    env = dict(__import__("os").environ, LLVM_CONFIG=str(LLVM_CONFIG))
    run("prospero-build", [SDK / "bin/prospero-clang++", *COMMON,
                           "-Wl,--build-id=none",
                           WORKER / "src/payload_selftest.cpp", SOURCE_IMPL,
                           "-o", out], env=env)
    # Wrapper-convention evidence: the call site of the raw trampoline.
    disasm = subprocess.run([str(LLVM_BIN / "llvm-objdump"), "-d", "--no-show-raw-insn",
                             str(out)], capture_output=True, text=True, env=env)
    (WORKER / "build/payload-full-disasm.txt").write_text(disasm.stdout)
    lines = disasm.stdout.splitlines()
    starts = [i for i, ln in enumerate(lines) if ln.startswith("0000") and "<_ZN12_GLOBAL__N_120selftest_raw_mincoreEmm>:" in ln]
    snippet = lines[starts[0]:starts[0] + 80] if starts else []
    (WORKER / "build/callsite-disasm.txt").write_text("\n".join(snippet) + "\n")
    # Static-link proof: the `syscall` trampoline symbol must be DEFINED in
    # the payload itself (syscalls.o in the static link, same class as the
    # composed candidate's runtime.map `.text.syscall` entries).
    nm = subprocess.run([str(LLVM_BIN / "llvm-nm"), str(out)],
                        capture_output=True, text=True, env=env)
    syscall_lines = [l for l in nm.stdout.splitlines() if l.endswith(" syscall") or "syscall" in l.split()[-1:]]
    (WORKER / "build/payload-syscall-symbols.txt").write_text(
        "\n".join(l for l in nm.stdout.splitlines() if "syscall" in l) + "\n")
    records.append({"name": "prospero-wrapper-evidence", "exit_code": disasm.returncode,
                    "disasm_lines": len(snippet), "call_site": "build/callsite-disasm.txt",
                    "syscall_symbols": "build/payload-syscall-symbols.txt"})
    return out


def main():
    t0 = time.time()
    for label, path, want in (("parser", WORKER / "src/modforge_loadlist.h", PARSER_HEADER_SHA),
                              ("main_lua", BUNDLE_MAIN_LUA, EXPECT_MAIN_LUA_SHA),
                              ("seed_validation", WORKER / "src/SeedValidation.hpp", SEED_VALIDATION_SHA)):
        got = sha256(path)
        if got != want:
            raise SystemExit(f"REFUSED: {label} source identity drifted: {got}")
        records.append({"name": f"pin-{label}", "exit_code": 0, "sha256": got})
    print("pinned inputs verified (parser header + bundle main.lua)")
    generate_bytes_header()
    host_bin = build_host()
    prospero_bin = build_prospero()
    builds = {
        "host": {"path": str(host_bin), "sha256": sha256(host_bin),
                 "bytes": host_bin.stat().st_size,
                 "build_id": "host-" + sha256(host_bin)[:12]},
        "prospero": {"path": str(prospero_bin), "sha256": sha256(prospero_bin),
                     "bytes": prospero_bin.stat().st_size,
                     "build_id": "prospero-" + sha256(prospero_bin)[:12]},
    }
    receipt = {
        "worker": "worker-payload-selftest",
        "utc_started_epoch": t0,
        "pin": {"modforge_loadlist.h": PARSER_HEADER_SHA,
                "bundle_main_lua": EXPECT_MAIN_LUA_SHA,
                "lineage_header": str(LINEAGE_INCLUDE / "Platform/NativeModSource.hpp"),
                "native_mod_source_impl": str(SOURCE_IMPL)},
        "commands": records,
        "builds": builds,
        "retries_allowed": MAX_BUILD_RETRIES,
        "labels": {"evidence_class": "separate-process standalone payload",
                   "never": "game-process"},
    }
    (WORKER / "build/build-receipt.json").write_text(json.dumps(receipt, indent=1) + "\n")
    print(json.dumps(builds, indent=1))


if __name__ == "__main__":
    main()
