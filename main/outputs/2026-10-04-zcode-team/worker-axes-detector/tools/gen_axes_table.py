#!/usr/bin/env python3
"""Generate src/axes_table.h mechanically from the upstream patternsleuth
engine_version.rs MARKERS/VERSIONS tables.

Source of truth (read-only):
  .superpowers/native-dependency-spike/ue4ss-native-patternsleuth-1/
      upstream/patternsleuth/src/resolvers/unreal/engine_version.rs

This tool never invents marker data: it parses the Rust literal tables and
re-emits them as C. Any upstream edit must be re-ingested by re-running it.
"""
import re
import sys
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.normpath(os.path.join(HERE, "..", "src"))
DEFAULT_RS = os.path.normpath(os.path.join(
    HERE, "..", "..", "..", "..",
    ".superpowers", "native-dependency-spike",
    "ue4ss-native-patternsleuth-1",
    "upstream", "patternsleuth", "src", "resolvers", "unreal",
    "engine_version.rs"))


def parse_rust_string(lit):
    """Decode a simple Rust string literal (no unicode escapes present in
    the marker table; handle the standard escapes anyway)."""
    assert lit[0] == '"' and lit[-1] == '"', lit
    body = lit[1:-1]
    out = []
    i = 0
    while i < len(body):
        c = body[i]
        if c == "\\":
            nxt = body[i + 1]
            mapping = {'n': '\n', 'r': '\r', 't': '\t', '\\': '\\', '"': '"',
                       "'": "'", '0': '\0'}
            out.append(mapping[nxt])
            i += 2
        else:
            out.append(c)
            i += 1
    return "".join(out)


def main():
    rs_path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_RS
    src = open(rs_path, "r", encoding="utf-8").read()

    # ---- VERSIONS table -------------------------------------------------
    vtab = re.search(r"const VERSIONS:\s*&\[EngineVersion\]\s*=\s*&\[(.*?)\];",
                     src, re.S).group(1)
    versions = [(int(a), int(b)) for a, b in
                re.findall(r"v\((\d+),\s*(\d+)\)", vtab)]
    assert len(versions) == len(set(versions)), "duplicate VERSIONS entry"
    vindex = {v: i for i, v in enumerate(versions)}

    # ---- MARKERS table --------------------------------------------------
    mtab = re.search(r"const MARKERS:\s*&\[Marker\]\s*=\s*&\[(.*?)\n\];",
                     src, re.S).group(1)
    markers = []
    for m in re.finditer(
            r'Marker\s*\{\s*string:\s*("(?:[^"\\]|\\.)*")\s*,'
            r'\s*gates:\s*&\[((?:[A-Za-z_][A-Za-z0-9_]*)?)\]\s*,'
            r'\s*first:\s*(None|Some\(\s*v\(\s*(\d+)\s*,\s*(\d+)\s*\)\s*\))\s*,'
            r'\s*last:\s*(None|Some\(\s*v\(\s*(\d+)\s*,\s*(\d+)\s*\)\s*\))\s*,?'
            r'\s*\}', mtab):
        s = parse_rust_string(m.group(1))
        gate = m.group(2) or ""
        first = None if m.group(3) == "None" else (int(m.group(4)), int(m.group(5)))
        last = None if m.group(6) == "None" else (int(m.group(7)), int(m.group(8)))
        assert gate in ("", "NotShipping", "DevOnly", "TestOrShipping",
                        "ShippingOnly", "WithStats"), gate
        if first is not None:
            assert first in vindex, f"first {first} not in VERSIONS"
        if last is not None:
            assert last in vindex, f"last {last} not in VERSIONS"
        assert len(s) > 0 and len(s) < 256, len(s)
        markers.append({
            "s": s,
            "gate": gate,
            "first": vindex[first] if first else 0xFF,
            "last": vindex[last] if last else 0xFF,
        })

    assert len(set(m["s"] for m in markers)) == len(markers), "duplicate marker"
    assert len(markers) == len(re.findall(r"Marker\s*\{", mtab)), \
        "parser missed at least one Marker row"

    # ---- UTF-16 code-unit pool ------------------------------------------
    units = []
    offs = []
    for m in markers:
        offs.append(len(units))
        for ch in m["s"]:
            units.append(ord(ch))
    # Decode-back self-check: (units, offs, lens) must reproduce the strings.
    for m, off in zip(markers, offs):
        rebuilt = "".join(chr(u) for u in units[off:off + len(m["s"])])
        assert rebuilt == m["s"], f"pool roundtrip failed for {m['s']!r}"

    # ---- Emit C ---------------------------------------------------------
    lines = []
    a = lines.append
    a("/* axes_table.h — marker table for the in-probe build-config/stats")
    a(" * detector. GENERATED by tools/gen_axes_table.py from the upstream")
    a(" * patternsleuth engine_version.rs MARKERS/VERSIONS tables; do not edit.")
    a(" *")
    a(" * Gate encoding mirrors the Rust Gate enum:")
    a(" *   0 = ungated (version-window marker), 1 = NotShipping,")
    a(" *   2 = DevOnly, 3 = TestOrShipping, 4 = ShippingOnly, 5 = WithStats.")
    a(" * first/last are indices into ig_axes_versions; 0xFF = unbounded.")
    a(" * Upstream: %s */" % os.path.basename(rs_path))
    a("#ifndef IG_AXES_TABLE_H")
    a("#define IG_AXES_TABLE_H")
    a("")
    a("#include <stdint.h>")
    a("")
    a("#define IG_AXES_MARKER_COUNT %d" % len(markers))
    a("#define IG_AXES_VERSION_COUNT %d" % len(versions))
    a("#define IG_AXES_VNONE 0xFF")
    a("")
    a("static const uint16_t ig_axes_versions[IG_AXES_VERSION_COUNT][2] = {")
    for i in range(0, len(versions), 6):
        a("    " + " ".join("{%d,%d}," % v for v in versions[i:i + 6]))
    a("};")
    a("")
    a("/* UTF-16 code units, concatenated. */")
    a("#define IG_AXES_POOL_LEN %d" % len(units))
    a("static const uint16_t ig_axes_pool[IG_AXES_POOL_LEN] = {")
    CH = 16
    for i in range(0, len(units), CH):
        a("    " + " ".join("0x%04x," % u for u in units[i:i + CH]))
    a("};")
    a("")
    a("typedef struct IgAxesMarker {")
    a("    uint16_t off;  /* first code unit in ig_axes_pool */")
    a("    uint16_t len;  /* code units */")
    a("    uint8_t  gate;")
    a("    uint8_t  first;")
    a("    uint8_t  last;")
    a("} IgAxesMarker;")
    a("")
    gate_ids = {"": 0, "NotShipping": 1, "DevOnly": 2, "TestOrShipping": 3,
                "ShippingOnly": 4, "WithStats": 5}
    a("static const IgAxesMarker ig_axes_markers[IG_AXES_MARKER_COUNT] = {")
    for m, off in zip(markers, offs):
        a("    {%d,%d,%d,%d,%d},  /* %s */" %
          (off, len(m["s"]), gate_ids[m["gate"]], m["first"], m["last"],
           m["s"][:48].replace("*/", "* /")))
    a("};")
    a("")
    a("#endif  /* IG_AXES_TABLE_H */")

    out_path = os.path.join(OUT_DIR, "axes_table.h")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s: %d markers, %d versions, %d code units" %
          (out_path, len(markers), len(versions), len(units)))


if __name__ == "__main__":
    main()
