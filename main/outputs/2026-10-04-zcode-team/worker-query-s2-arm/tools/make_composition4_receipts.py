#!/usr/bin/env python3
"""Generate the composition-4 attestation receipts (replace-receipt + extra-receipt).

Merged replace-receipt = worker-composition-3's replace-receipt (bootstrap pair,
byte-identical) PLUS this worker's additions:
  - the staged S2-arm UnrealInitializer.cpp (replacement source)
  - the five headers the controller stages into ue4ss-native-tick-file-owner-1/include/
    (glob-pinned by the build script; listed here so staging is hash-verified too)
  - the seven .superpowers headers the supplier extra unit's dependency closure
    adds (admitted ONLY through the rr fallback; never silently)
Extra-receipt = hash attestation of the two new extra units' sources.
Writes only inside this worker output dir.
"""
import hashlib
import json
from pathlib import Path

WHAT = Path("/WORKSPACE/.codex/worktrees/translation-core/what")
TEAM = WHAT / "outputs/2026-10-04-zcode-team"
ME = TEAM / "worker-query-s2-arm"
OUT = ME / "integration-patch/receipts"


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


rr = json.loads((TEAM / "worker-composition-3/replace-receipt.json").read_text())
files = dict(rr["files"])

files[str(ME / "staging/UnrealInitializer.cpp")] = sha(ME / "staging/UnrealInitializer.cpp")

W = WHAT / ".superpowers/native-dependency-spike/ue4ss-native-tick-file-owner-1"
staged_headers = {
    "NativeQueryHarness.hpp": TEAM / "worker-query-harness/src/NativeQueryHarness.hpp",
    "runtime_owner.hpp": TEAM / "worker-composition-3/bootstrap-stage/native-coherent-runtime-1/source/bootstrap/runtime_owner.hpp",
    "activated_mod_source.hpp": TEAM / "worker-composition-3/bootstrap-stage/native-coherent-runtime-1/source/bootstrap/activated_mod_source.hpp",
    "ue4ss_backend.hpp": TEAM / "worker-composition-3/bootstrap-stage/native-coherent-runtime-1/source/bootstrap/ue4ss_backend.hpp",
    "modforge_activation.h": TEAM / "worker-installer-ps5io/vendored/modforge_activation.h",
}
for name, src in staged_headers.items():
    files[str(W / "include" / name)] = sha(src)

for dep in json.loads((ME / "probe/supplier-probe/superpowers-deps.json").read_text()):
    files[dep] = sha(dep)

merged = {
    "bundle": "composition-4 (S2-arm initializer + query-harness/ack-supplier extras)",
    "provenance": {
        "base": "worker-composition-3/replace-receipt.json (bootstrap pair, byte-identical inclusion)",
        "initializer": "staged S2-arm UnrealInitializer.cpp; base unit pinned at 66691a88... in the composition base receipt; patch generated by worker-query-s2-arm/tools/make_initializer_staging.py and compile-proven under the exact affected-unit argv",
        "staged_headers": "controller copies these five files into ue4ss-native-tick-file-owner-1/include/ (flat, glob-pinned) before composing; listed here so any byte drift refuses the build",
        "port_headers": "unpinned .superpowers dependencies of the supplier extra unit; admitted exclusively through the build script's rr fallback, never silently",
    },
    "files": dict(sorted(files.items())),
    "include_dir_map": rr["include_dir_map"],
    "include_dir_map_note": rr["include_dir_map_note"],
}
OUT.mkdir(parents=True, exist_ok=True)
(OUT / "composition4-replace-receipt.json").write_text(json.dumps(merged, indent=1) + "\n")

extra = {
    "bundle": "composition-4 extra units (native-query-harness + module-runtime-ack-supplier)",
    "provenance": {
        "native-query-harness": "worker-query-harness deliverable, unchanged bytes (REPORT sha column); target object byte-identical to this worker's probe (1eb11c7a...), zero new undefined symbols vs composition-3",
        "module-runtime-ack-supplier": "authored by worker-query-s2-arm (WIRING-SPEC S1/S2/S3); target compile probe clean, imports classify into composed units + harness unit + frozen import contract",
    },
    "files": {
        str(TEAM / "worker-query-harness/src/NativeQueryHarness.hpp"): sha(TEAM / "worker-query-harness/src/NativeQueryHarness.hpp"),
        str(TEAM / "worker-query-harness/src/NativeQueryHarness.cpp"): sha(TEAM / "worker-query-harness/src/NativeQueryHarness.cpp"),
        str(ME / "integration-patch/new-units/runtime_ack_supplier.hpp"): sha(ME / "integration-patch/new-units/runtime_ack_supplier.hpp"),
        str(ME / "integration-patch/new-units/runtime_ack_supplier.cpp"): sha(ME / "integration-patch/new-units/runtime_ack_supplier.cpp"),
    },
}
(OUT / "composition4-extra-receipt.json").write_text(json.dumps(extra, indent=1) + "\n")
print("wrote", OUT / "composition4-replace-receipt.json", f"({len(files)} files)")
print("wrote", OUT / "composition4-extra-receipt.json")
