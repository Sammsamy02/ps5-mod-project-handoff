#!/usr/bin/env python3
"""run_host_checks.py — worker-writability-probe-build host suite.

Compiles the exec-write probe machinery for the HOST (macOS) twice —
ARMED (sceKernelMprotect = scripted mock) and UNARMED (compile-time stub)
— against the SAME 13-row test table, runs both binaries, and then
validates EVERY emitted JSONL record with json.loads plus per-record
ordering/grammar assertions (the worker-c2-probe writer_host pattern).
Outputs: out-armed.jsonl, out-unarmed.jsonl, json-validation.txt,
test-run.txt. Local only; no native/console execution.
"""
import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parent / "src"

ROWS = [
    # (addr, from, to, pages, confirmed, note)
    (0x180000000, 0x4, 0x5, 1, 1, "x2rx ok on confirmed row"),
    (0x185000000, 0x4, 0x5, 1, 0, "design-unconfirmed: must never attempt"),
    (0x181000000, 0x4, 0x7, 1, 1, "x2rwx far page, scripted ENOMEM"),
    (0x183000000, 0x4, 0x5, 1, 1, "from_prot mismatch: vmmap says 0x5"),
    (0x184000000, 0x4, 0x5, 1, 1, "uncovered: no vmmap record"),
    (0x182000000, 0x4, 0x7, 1, 1, "x2rwx far page ok (write test)"),
] + [
    (0x190000000 + 0x100000 * k, 0x4, 0x5, 1, 1, f"budget row k={k}")
    for k in range(7)
]

CONFIG_TAIL = """
// mprotect verification (brief): the frozen 191-import contract carries NO
// mprotect-class strong row; kernel_mprotect appears only weak/absent.
"""


def gen_tables():
    for variant, armed in (("gen-armed", 1), ("gen-unarmed", 0)):
        g = HERE / variant / "generated"
        g.mkdir(parents=True, exist_ok=True)
        (g / "ingame_config.h").write_text(
            "// GENERATED by run_host_checks.py — host test config.\n"
            "#pragma once\n"
            '#define IG_BUILD_ID "igd1-host-test"\n'
            '#define IG_LOG_PATH "out-host.jsonl"\n'
            '#define IG_MIRROR_LOG_PATH "out-host-mirror.log"\n'
            f"#define IG_XWP_MPROTECT_ARMED {armed}\n" + CONFIG_TAIL)
        body = ",\n".join(
            '    {{0x{0:x}ull, 0x{1:x}ull, 0x{2:x}ull, {3}u, {4}u, "{5}"}}'
            .format(*r) for r in ROWS)
        (g / "xwp_transitions.h").write_text(
            "/* GENERATED by run_host_checks.py. */\n"
            "#ifndef GENERATED_XWP_TRANSITIONS_H\n"
            "#define GENERATED_XWP_TRANSITIONS_H\n"
            '#include "exec_write_probe.h"\n'
            "extern const XwpTransition xwp_transitions[];\n"
            "extern const unsigned xwp_transitions_count;\n"
            "#endif\n")
        (g / "xwp_transitions.c").write_text(
            "/* GENERATED by run_host_checks.py. */\n"
            '#include "exec_write_probe.h"\n'
            "const XwpTransition xwp_transitions[] = {\n" + body + "\n};\n"
            f"const unsigned xwp_transitions_count = {len(ROWS)}u;\n")


def compile_and_run(variant: str, armed: int) -> Path:
    g = HERE / variant
    out = HERE / ("test_exec_write_probe_" + variant)
    objs = []
    host_srcs = [
        (SRC / "exec_write_probe.c"), (SRC / "record_sink.c"),
        (SRC / "ingame_libc.c"), (SRC / "vmmap_walk.c"),
        (g / "generated" / "xwp_transitions.c"),
        (HERE / "xwp_host_shims.c"),
        (HERE / "test_exec_write_probe_host.c"),
    ]
    for src in host_srcs:
        o = g / (src.stem + ".o")
        r = subprocess.run(["clang", "-Wall", "-Wextra", "-Werror", "-g", "-O1",
                            "-I", str(g), "-I", str(g / "generated"),
                            "-I", str(SRC), "-I", str(HERE),
                            "-c", str(src), "-o", str(o)],
                           capture_output=True, text=True)
        if r.returncode != 0:
            sys.exit(f"host compile FAILED ({src}):\n{r.stderr}")
        objs.append(o)
    r = subprocess.run(["clang", "-o", str(out)] + [str(o) for o in objs],
                       capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(f"host link FAILED:\n{r.stderr}")
    jsonl = HERE / f"out-{variant}.jsonl"
    mirror = HERE / f"out-{variant}-mirror.log"
    for p in (jsonl, mirror):
        if p.exists():
            p.unlink()
    run = subprocess.run([str(out), str(jsonl), str(mirror), str(armed)],
                         capture_output=True, text=True)
    if run.returncode != 0:
        sys.exit(f"{variant} binary FAILED rc={run.returncode}:\n"
                 f"{run.stdout}\n{run.stderr}")
    print(run.stdout.strip())
    return jsonl


ORDER = {"row": 0, "vmmap_persist": 1, "attempt": 2, "rw_test": 3,
         "restore": 4, "post_restore": 5, "refusal": 2,
         "table_empty": 0, "summary": 9}
ATTEMPT_OK, RESTORE_OK, IMPORT_ABSENT = 8, 10, 11


def validate(jsonl: Path, variant: str, lines_out: list) -> None:
    rows = [json.loads(l) for l in jsonl.read_text().splitlines() if l.strip()]
    lines_out.append(f"{variant}: {len(rows)} records, all json.loads OK")
    armed = variant == "gen-armed"
    per_row = {}
    last_seq = 0
    cur = None
    for rec in rows:
        assert rec["marker"] == "modbridge.execwriteprobe", rec
        assert rec["schema"] == 1 and "build_id" in rec
        assert isinstance(rec["seq"], int) and rec["seq"] >= last_seq
        last_seq = rec["seq"]
        exp, f = rec["exp"], rec["fields"]
        if exp == "row":
            cur = rec["seq"]
            assert cur not in per_row
            per_row[cur] = {"row": f}
        elif exp in ("vmmap_persist", "attempt", "rw_test", "restore",
                     "post_restore", "refusal"):
            per_row[cur]["seq_" + exp] = f
        elif exp == "summary":
            s = f
            assert s["rows_seen"] == 13 and s["attempt_budget"] == 8
            assert s["attempts_used"] == 8
            assert s["rows_attempted"] == 8
            assert s["budget_exhausted"] == (1 if armed else 1)
            assert s["mirror_failures"] == 0
            assert s["armed"] == (1 if armed else 0)
    # group row streams by contiguity: each "row" starts a group that must
    # be closed by refusal or post_restore before the next "row".
    groups = []
    for rec in rows:
        if rec["exp"] == "row":
            groups.append([rec])
        elif groups and rec["exp"] != "summary":
            groups[-1].append(rec)
    n_attempted = n_refused = n_skipped = 0
    for grp in groups:
        exps = [r["exp"] for r in grp]
        assert exps[0] == "row"
        if exps[1] == "refusal":
            n_skipped += 1
            assert grp[1]["fields"]["no_memory_touched"] == 1
            assert len(exps) == 2, exps
            continue
        if "rw_test" in exps:
            assert exps == ["row", "vmmap_persist", "attempt", "rw_test",
                            "restore", "post_restore"], exps
        else:
            assert exps == ["row", "vmmap_persist", "attempt", "restore",
                            "post_restore"], exps
        n_attempted += 1
        f_attempt = grp[2]["fields"]
        outcomes = [f_attempt["outcome"]]
        outcomes.append(grp[exps.index("restore")]["fields"]["outcome"])
        if armed:
            assert IMPORT_ABSENT not in outcomes, grp
            if f_attempt["outcome"] == ATTEMPT_OK:
                pass
            else:
                assert f_attempt["outcome"] in (ATTEMPT_OK,
                                                7), f_attempt
        else:
            assert outcomes == [IMPORT_ABSENT, IMPORT_ABSENT], outcomes
        post = grp[-1]["fields"]
        # The mock map never mutates, so a correct restore (or a no-op stub
        # failure in unarmed) must re-observe from_prot in both variants.
        assert post["restored_matches_from_prot"] == 1, post
    assert n_attempted == 8, n_attempted
    if armed:
        rw = [g for g in groups if any(r["exp"] == "rw_test" for r in g)]
        # read test on EVERY successful attempt (8 total, minus the
        # scripted-failure row = 7 rw_test records)...
        assert len(rw) == 7, f"7 read-tested rows, got {len(rw)}"
        # ...and exactly ONE write-tested row (the X->RWX far page):
        w = [g for g in rw
             if next(r for r in g if r["exp"] == "rw_test")["fields"]["write_tested"]]
        assert len(w) == 1, f"exactly one write-tested row, got {len(w)}"
        rwf = next(r for r in w[0] if r["exp"] == "rw_test")["fields"]
        assert rwf["recovered"] == 1 and rwf["read_done"] == 1
        refs = [g[1]["fields"]["outcome"] for g in groups
                if g[1]["exp"] == "refusal"]
        assert refs.count(3) == 2, refs    # SKIP_BUDGET x2
        assert refs.count(2) == 1, refs    # SKIP_NOT_CONFIRMED x1
        assert refs.count(5) == 1, refs    # REFUSE_NOT_COVERED x1
        assert refs.count(6) == 1, refs    # REFUSE_PROT_MISMATCH x1
    lines_out.append(f"{variant}: ordering/grammar/budget assertions OK")


def main():
    gen_tables()
    lines = []
    for variant, armed in (("gen-armed", 1), ("gen-unarmed", 0)):
        jsonl = compile_and_run(variant, armed)
        validate(jsonl, variant, lines)
    (HERE / "json-validation.txt").write_text("\n".join(lines) + "\n")
    summary = ["worker-writability-probe-build HOST SUITE: PASS",
               "armed binary: 13-row table, 8/8 budget attempts, restore "
               "pairing, 1 rw_test with recovery, 5 refusals/skips with "
               "zero mprotect calls",
               "unarmed binary: 13-row table, 8 stub attempts (outcome 11), "
               "ZERO mock mprotect calls",
               "every JSONL line parsed by json.loads (json-validation.txt)"]
    (HERE / "test-run.txt").write_text("\n".join(summary) + "\n")
    print("\n".join(summary))


if __name__ == "__main__":
    main()
