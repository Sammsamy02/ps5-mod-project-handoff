// Labeled change 2: wiring-guard refusal counter (never expected nonzero).
unsigned g_nqh_wiring_refusals;

// Labeled change 3: bounded pause backoff for the snapshot retry loop.
static inline void nqh_pause_spin() noexcept
{
    for (int i = 0; i < 64; ++i)
    {
#if defined(__x86_64__) || defined(__i386__)
        __builtin_ia32_pause();
#else
        __asm__ volatile("" ::: "memory");
#endif
    }
}

