// See NativeQueryHarness.hpp for the milestone contract. Implementation notes:
//  * The ONLY writer of record_ is the accepted game-thread Tick path
//    (identity checks admit exactly one thread), guarded by the seqlock.
//  * Refusal paths never touch record_; they only advance diagnostic
//    counters, so a refusal can never publish or corrupt a partial record.
//  * An engine read that faults or throws inside the noexcept Tick entry
//    terminates the process by design: masking a real engine fault would be
//    dishonest evidence for this milestone.
//
// ---------------------------------------------------------------------------
// FREESTANDING ADD-ON VARIANT (LABELED CHANGES ONLY — worker-record-sink-addon,
// qdrv1 build, team 2026-10-04). Vendored byte-identical from
// worker-query-harness/src/NativeQueryHarness.cpp, then edited as follows.
// The record/seqlock/refusal/formatter logic (TrySnapshot, SnapshotDispatch-
// Counters, OnEngineTickDispatch, publish_terminal, record_refusal, begin/end
// write, FormatRecordJsonLine, all *Name helpers, the QueryResultRecord and
// counter layout) is UNTOUCHED. The edits exist because this PRX is a
// freestanding igd-lineage module: no libc++ABI unwinder, no exceptions, and
// no RC::Unreal headers (the composed runtime owns those).
//   1. The build defines NATIVE_QUERY_HARNESS_HOST_TEST ON TARGET. In this
//      build the macro's ONLY effect is excluding the RC::Unreal default
//      bindings (lines guarded by it below); the host tests compile the exact
//      same TU the target links. The add-on wires its own four probes through
//      the documented injectable seam InstallEngineBindings() (hpp:155-173).
//   2. Every `throw std::logic_error` (wiring guards only: InstallEngine-
//      Bindings x3, InstallDefaultEngineBindings x1, ArmLayoutGate x3) is
//      replaced by ++g_nqh_wiring_refusals + return. The guards' ORDER and
//      conditions are unchanged; the driver calls each wiring function at
//      most once with precondition-checked arguments, so a nonzero counter
//      is a LOUD wiring bug, reported in the startup/summary records.
//   3. std::this_thread::yield() in TrySnapshot -> nqh_pause_spin() (bounded
//      x86 pause loop; the seqlock retry bound kSnapshotMaxRetries is
//      unchanged). <thread> is dropped.
//   4. std::memcpy (32-byte gate_source copy in publish_terminal) ->
//      ig_memcpy (ingame_libc.h, byte-identical lineage helper). <cstring>
//      is dropped. Any 128-byte record struct copy lowers to plain
//      load/store or the PRX-local memcpy shim (qh_libc.c); no import.
// Diff receipt: receipts/nqh-addon-variant.diff (generated by the build).
// ---------------------------------------------------------------------------

