#!/usr/bin/env python3
"""gen_host_config.py — HOST TEST ONLY (worker-c2-probe). Generates
tests/generated/ingame_config.h from EXPECTED-VALUES-OFFLINE.json. The real
build script generates its own config (with the real build id); this copy
exists so the host logic test compiles independently of the PRX build.
Candidate BYTES are still NOT written here (only lengths)."""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
WORKER = HERE.parent
ev = json.loads((WORKER / "EXPECTED-VALUES-OFFLINE.json").read_text())

IMAGE_BASE = 0x400000
EXEC_END = 0x787C000
lines = [
    "// GENERATED by tests/gen_host_config.py — host test only.\n"
    "#pragma once\n",
    '#define IG_BUILD_ID "igf7-HOSTTEST"\n',
    '#define IG_LOG_PATH "/tmp/igf7-hosttest.jsonl"\n',
    f"#define IG_IMAGE_BASE 0x{IMAGE_BASE:x}ull\n",
    f"#define IG_EXEC_EXPECTED_END 0x{EXEC_END:x}ull\n",
    f"#define IG_EXEC_EXPECTED_BYTES 0x{EXEC_END - IMAGE_BASE:x}ull\n",
    "#define IG_C2_COUNT 5\n",
    "#define IG_C2_MAX_LEN 64u\n",
]
for c in ev["candidates"]:
    cid = c["id"]
    vaddr = int(c["vaddr"], 16)
    fileoff = int(c["derived_file_offset"], 16)
    lines.append(f"#define IG_C2_{cid}_VADDR 0x{vaddr:x}ull\n")
    lines.append(f"#define IG_C2_{cid}_RT 0x{IMAGE_BASE + vaddr:x}ull\n")
    lines.append(f"#define IG_C2_{cid}_FILEOFF 0x{fileoff:x}ull\n")
    lines.append(f"#define IG_C2_{cid}_LEN {c['len']}u\n")

out = HERE / "generated"
out.mkdir(parents=True, exist_ok=True)
(out / "ingame_config.h").write_text("".join(lines))
print("wrote", out / "ingame_config.h")
