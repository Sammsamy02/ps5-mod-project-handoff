#!/usr/bin/env python3
"""Apply the agent-AA engine-binary FUObjectArray offset correction to the l25 profile.

Mechanics follow the AM profile-fix template (profile-fix.diff.tmpl) with the
documented DROP PATH for UObjectDeleteListenersCritical implemented: the value is
verified (0x78) but NOT published, because NativeLayoutSchema.inc has no row for
FUObjectArray::UObjectDeleteListenersCritical, NativeLayoutBinding.cpp:74 throws
"Unknown native member" on schema-less INI keys, require_layout refuses absent
kRequiredMembers pins, and no port/l25 code ever locks it (LockGUObjectArray
stubs). Publishing it would require schema+binding machinery outside the
value-only 4-file fix scope.

Value-only correction of the five EXISTING profile fields, exactly per AL's edit
scope (facts JSON, INI declarations header, RuntimeBuildProfile pins) plus the
run_tests.py prior-93 pin block (the "old pins" the fix is authorized to update);
preflight.cpp is regenerated by run_tests.py from the INI. Digest chain
recomputed with the existing mechanism (l19-r4 generate_profile.generate).
Originals stay pinned to l23 (Z9 one-hop law); generate_overlay.py is NOT
re-run (it would regenerate from l23 and erase the correction).

Usage:
  python3 apply_engine_binary_fix.py --values aa-values-engine-binary.json \
      [--root <profile-root>] [--remap-from <live-profile-root>] [--allow-live]
"""
from pathlib import Path
import argparse, configparser, hashlib, json, runpy

HERE = Path(__file__).resolve().parent
LIVE_ROOT = HERE.parents[0] / 'profile'
OLD_SOURCE = 'retained authenticated image/static evidence'
OLD_DIGEST = '4667891671fda00328bc61e1029c86058b1f558df4c4f4ae0922aa18ddd13317'
FIELDS = {  # name -> (old_dec, old_hex)
    'FUObjectArray::UObjectCreateListeners': (104, '0x68'),
    'FUObjectArray::UObjectDeleteListeners': (120, '0x78'),
    'FUObjectArray::PrimarySerialNumber': (176, '0xb0'),
    'FUObjectArray::bShouldRecycleObjectIndices': (180, '0xb4'),
    'FUObjectArray::UEP_TotalSize': (184, '0xb8'),
}
sha = lambda p: hashlib.sha256(Path(p).read_bytes()).hexdigest()
die = lambda m: (_ for _ in ()).throw(SystemExit('apply_engine_binary_fix: ' + m))


def facts_fix(root, values):
    f = root / 'profiles/townfall-build-facts.json'
    p = json.loads(f.read_text())
    byname = {m['name']: m for m in p['required_members']}
    if 'FUObjectArray::UObjectDeleteListenersCritical' in byname:
        die('critical-section fact already present; refusing to run twice')
    for name, (old_dec, _hex) in FIELDS.items():
        row = byname.get(name)
        if row is None:
            die('missing existing fact row ' + name)
        if row['offset'] != old_dec or row['source'] != OLD_SOURCE:
            die('unexpected prior state for %s: offset=%r source=%r' % (name, row['offset'], row['source']))
        row['offset'] = values[name.split('::')[1]]
        row['source'] = values['source']
    f.write_text(json.dumps(p, indent=2) + '\n')
    return p


def regen_runtime_build_profile(root, p):
    ws = HERE.parents[2]  # <worktree>/what (from this script's stable location, not the sandbox root)
    prior = ws / 'outputs/2026-10-07-l19-local-profile-r4'
    old_rbp = (root / 'units/RuntimeBuildProfile.hpp').read_text()
    if OLD_DIGEST not in old_rbp:
        die('RuntimeBuildProfile.hpp does not carry the expected prior digest')
    g = runpy.run_path(str(prior / 'profiles/generate_profile.py'))
    g['generate'].__globals__['root'] = root
    digest = g['generate'](p)
    return digest


def declarations_fix(root, values, digest):
    f = root / 'units/CompiledNativeLayoutDeclarations.hpp'
    strings = [json.loads(x.rstrip(',')) for x in f.read_text().splitlines() if x.startswith('"')]
    if len(strings) != 4 or strings[3] != OLD_DIGEST or strings[2] != 'compiled-audited-townfall-l25':
        die('unexpected declarations header state')
    ini = strings[0]
    for name, (old_dec, old_hex) in FIELDS.items():
        key = name.split('::')[1]
        old = key + '=' + old_hex + '\n'
        new = key + '=' + hex(values[key]) + '\n'
        if ini.count(old) != 1:
            die('INI slot not unique for %s (%d matches)' % (key, ini.count(old)))
        ini = ini.replace(old, new)
    if 'UObjectDeleteListenersCritical' in ini:
        die('critical-section key must not be published')
    strings[0] = ini
    strings[3] = digest
    f.write_text('#pragma once\nnamespace RC::Platform::NativeLayouts {\ninline constexpr CompiledNativeLayoutDeclarations kCompiledNativeLayoutDeclarations{\n'
                 + ',\n'.join(json.dumps(s) for s in strings) + '\n};\n}\n')


RUNTESTS_OLD = (
    "assert p['required_members'][:69]==base['required_members'] and p['required_vtables']==base['required_vtables']\n"
    "assert len(p['required_members'])+len(p['required_vtables'])==93+changes['new_promoted_facts']==98\n"
    "promoted=[{k:m[k] for k in ('name','offset','width')} for m in p['required_members'][69:]]\n")


def run_tests_fix(root, values):
    f = root / 'tests/run_tests.py'
    t = f.read_text()
    if 'CORRECTED={' in t:
        return  # already fixed (idempotent on re-run for hash recompute flows)
    if t.count(RUNTESTS_OLD) != 1:
        die('run_tests.py immutability block not found verbatim')
    corr = ','.join(json.dumps(k) + ':' + str(values[k.split('::')[1]]) for k in FIELDS)
    new = (
        "# l25 engine-binary offset fix: FUObjectArray listener-zone offsets corrected in place from\n"
        "# agent-AA disassembly of the authenticated image; corrected names are excluded from the\n"
        "# retained-93 byte-identity check and pinned to the corrected values; no new facts appended\n"
        "# (UObjectDeleteListenersCritical verified 0x78 but NOT published: no NativeLayoutSchema.inc\n"
        "# row, NativeLayoutBinding.cpp:74 throws on unknown members, require_layout refuses absent\n"
        "# pins, and the port never locks it).\n"
        "CORRECTED={" + corr + "}\n"
        "retained_p=[m for m in p['required_members'][:69] if m['name'] not in CORRECTED];retained_b=[m for m in base['required_members'][:69] if m['name'] not in CORRECTED]\n"
        "assert retained_p==retained_b and p['required_vtables']==base['required_vtables']\n"
        "fixed=[m for m in p['required_members'] if m['name'] in CORRECTED]\n"
        "assert len(fixed)==5 and {m['name']:m['offset'] for m in fixed}==CORRECTED\n"
        "assert all('agent-AA-offset-verify.md' in m['source'] for m in fixed)\n"
        "assert len(p['required_members'])+len(p['required_vtables'])==93+changes['new_promoted_facts']==98\n"
        "promoted=[{k:m[k] for k in ('name','offset','width')} for m in p['required_members'][69:]]\n")
    t = t.replace(RUNTESTS_OLD, new)
    old_label = "'prior93_retained':True,"
    new_label = "'prior93_retained':'88 untouched + 5 FUObjectArray listener-zone corrected in place (l25 engine-binary fix)',"
    if t.count(old_label) != 1:
        die('RESULTS prior93 label not found')
    t = t.replace(old_label, new_label)
    old_print = ", prior93 immutable, l24 corroborated')"
    new_print = ", prior88 immutable + 5 listener-zone corrected, l24 corroborated')"
    if t.count(old_print) != 1:
        die('final print line not found')
    t = t.replace(old_print, new_print)
    f.write_text(t)


def changes_rewrite(root, values, digest, remap_from):
    f = root / 'CHANGES.json'
    d = json.loads(f.read_text())
    d['profile_digest'] = digest
    d['prior_facts_retained'] = 88  # 93 retained facts minus the 5 corrected in place
    d['listener_corrected_facts'] = list(FIELDS)
    d['listener_new_facts'] = 0
    d['listener_fix_provenance'] = values['provenance']
    d['listener_unpublished_offsets'] = dict(values['provenance']['verified_not_published'],
        reason='NativeLayoutSchema.inc has no UObjectDeleteListenersCritical/ObjObjectsCritical/ObjAvailableList rows; NativeLayoutBinding.cpp:74 throws on unknown members; require_layout refuses absent kRequiredMembers pins; no consumer (port never locks the critical section - LockGUObjectArray stubs). Publishing needs schema+binding machinery outside the value-only fix scope.')
    d['scope'] += (' l25 engine-binary offset fix: FUObjectArray UObjectCreateListeners/UObjectDeleteListeners/'
                   'PrimarySerialNumber/bShouldRecycleObjectIndices/UEP_TotalSize corrected in place from agent-AA '
                   'engine-binary disassembly (S=0x18 lazy critical section; old 0xB0/0xB4/0xB8 pins pointed into '
                   'adjacent BSS); UObjectDeleteListenersCritical=0x78 verified but not published.')
    d['regenerate'] = ('SUPERSEDED-BY-L25-ENGINE-BINARY-FIX: do NOT re-run generate_overlay.py after this correction '
                       '(it regenerates from l23 and would erase it). Applied by '
                       + str(HERE / 'apply_engine_binary_fix.py') + ' with ' + str(HERE / 'aa-values-engine-binary.json')
                       + '; see outputs/2026-10-08-l25-prep/agent-AS-profile-fix.md.')
    rf = str(Path(remap_from).resolve()) if remap_from is not None else None
    for row in d['files']:
        cand = Path(row['candidate'])
        if rf is not None:
            if str(cand).startswith(rf + '/'):
                cand = Path(str(cand).replace(rf, str(root), 1))
            row['candidate'] = str(cand)
        if not cand.exists():
            die('candidate missing: ' + str(cand))
        row['candidate_sha256'] = sha(cand)
    if rf is not None:
        d['include_directories'] = [x.replace(rf, str(root)) for x in d['include_directories']]
    f.write_text(json.dumps(d, indent=2) + '\n')
    return d


def validate(root, values, digest):
    p = json.loads((root / 'profiles/townfall-build-facts.json').read_text())
    recomputed = hashlib.sha256(json.dumps(p, sort_keys=True, separators=(',', ':')).encode()).hexdigest()
    if recomputed != digest:
        die('digest mismatch after rewrite')
    names = [m['name'] for m in p['required_members']]
    if len(names) != len(set(names)) or len(names) != 74:
        die('required_members must stay 74 unique rows')
    byname = {m['name']: m for m in p['required_members']}
    for name in FIELDS:
        if byname[name]['offset'] != values[name.split('::')[1]]:
            die('fact not corrected: ' + name)
    if any('UObjectDeleteListenersCritical' == n.split('::')[1] for n in names):
        die('critical-section fact leaked into required_members')
    ini_hpp = (root / 'units/CompiledNativeLayoutDeclarations.hpp').read_text()
    rbp = (root / 'units/RuntimeBuildProfile.hpp').read_text()
    ch = json.dumps(json.loads((root / 'CHANGES.json').read_text()))
    for label, text in (('INI hpp', ini_hpp), ('RuntimeBuildProfile', rbp), ('CHANGES', ch)):
        if digest not in text:
            die('digest missing from ' + label)
    for label, text in (('INI hpp', ini_hpp), ('RuntimeBuildProfile', rbp), ('facts', json.dumps(p))):
        if 'UObjectDeleteListenersCritical' in text:
            die('critical-section published in ' + label)
    strings = [json.loads(x.rstrip(',\n ')) for x in ini_hpp.splitlines() if x.lstrip().startswith('"')]
    c = configparser.ConfigParser()
    c.optionxform = str
    c.read_string(strings[0])
    for section in c.sections():
        if section == 'NativeLayout':
            continue
        total = int(c.get(section, 'UEP_TotalSize'), 0)
        if total <= 0:
            die('section without positive UEP_TotalSize: ' + section)
        for key, v in c[section].items():
            if key != 'UEP_TotalSize' and int(v, 0) >= total:
                die('member outside class size: ' + section + '::' + key)
    for key, member in (('UObjectCreateListeners', 'FUObjectArray::UObjectCreateListeners'),
                        ('UObjectDeleteListeners', 'FUObjectArray::UObjectDeleteListeners'),
                        ('PrimarySerialNumber', 'FUObjectArray::PrimarySerialNumber'),
                        ('bShouldRecycleObjectIndices', 'FUObjectArray::bShouldRecycleObjectIndices'),
                        ('UEP_TotalSize', 'FUObjectArray::UEP_TotalSize')):
        if int(c.get('FUObjectArray', key), 0) != values[key]:
            die('INI value wrong for ' + key)
        pin = '{"%s",true,%d,0,' % (member, values[key])
        if pin not in rbp:
            die('RuntimeBuildProfile pin wrong for ' + member)
    pre = (root / 'units/JoinedLayoutPreflight.hpp').read_text()
    rows = [l for l in pre.splitlines() if l.startswith(' {"')]
    if len(rows) != 66 or 'static_assert(sizeof(kKeys)/sizeof(kKeys[0])==66);' not in pre:
        die('JoinedLayoutPreflight must stay at 66 rows (untouched)')
    rt = (root / 'tests/run_tests.py').read_text()
    if 'CORRECTED={' not in rt:
        die('run_tests.py fix hunks missing')
    return {'required_members': len(names), 'joined_rows': len(rows), 'digest': digest}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--values', required=True)
    ap.add_argument('--root', default=str(LIVE_ROOT))
    ap.add_argument('--remap-from', default=None)
    ap.add_argument('--allow-live', action='store_true')
    args = ap.parse_args()
    root = Path(args.root).resolve()
    values = json.loads(Path(args.values).read_text())
    for f in ('UObjectCreateListeners', 'UObjectDeleteListeners', 'PrimarySerialNumber',
              'bShouldRecycleObjectIndices', 'UEP_TotalSize', 'source'):
        if f not in values:
            die('values file missing field ' + f)
    total = values['UEP_TotalSize']
    for f in ('UObjectCreateListeners', 'UObjectDeleteListeners', 'PrimarySerialNumber', 'bShouldRecycleObjectIndices'):
        if not 0 <= values[f] < total:
            die('member at/after UEP_TotalSize (INI guard would refuse): ' + f)
    if root == LIVE_ROOT and not args.allow_live:
        die('refusing to touch the live profile without --allow-live')
    p = facts_fix(root, values)
    digest = regen_runtime_build_profile(root, p)
    declarations_fix(root, values, digest)
    run_tests_fix(root, values)
    changes_rewrite(root, values, digest, args.remap_from)
    summary = validate(root, values, digest)
    summary.update({'root': str(root),
                    'new_hashes': {Path(r['candidate']).name: r['candidate_sha256']
                                   for r in json.loads((root / 'CHANGES.json').read_text())['files']}})
    print(json.dumps(summary, indent=2))


if __name__ == '__main__':
    main()
