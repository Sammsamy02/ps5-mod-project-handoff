static constexpr size_t kChunkLimit = 32; // simulated target short-write size

// extern "C": PosixFile.cpp's unistd.h prototype (macro-rewritten by
// -Dwrite=chunked_write) carries C linkage, so the definition must match.
extern "C" ssize_t chunked_write(int fd, const void* buf, size_t count)
{
    if (count > kChunkLimit) count = kChunkLimit;
    return ::write(fd, buf, count);
}

#if HARNESS_CONVERSION == 1
// Deployed-binary simulation (CE's buggy_codecvt_widen): the PS5 SDK libc++
// short-wchar codecvt stride corruption observed in the console UE4SS.log —
// every other output unit is a NUL.
static auto deployed_nul_widen(const char* p) -> RC::StringType
{
    RC::StringType out;
    while (*p)
    {
        out.push_back(static_cast<RC::CharType>(*p));
        out.push_back(static_cast<RC::CharType>('\0'));
        ++p;
    }
    return out;
}
#endif

static const char* kPayload =
        "[TownfallItemSpawner] Scan failed: ue4ss/Mods/TownfallItemSpawner/Scripts/main.lua:"
        " Tried calling <GetItemIDFromDeprecatedEnum> but the UFunction is a nullptr: "
        "in method 'GetItemIDFromDeprecatedEnum'"; // long line: length-dependent tail loss on console

static auto lua_line(const char* payload) -> RC::StringType
{
    RC::StringType s = STR("[Lua] ");
#if HARNESS_CONVERSION == 1
    s += deployed_nul_widen(payload);
#elif HARNESS_CONVERSION == 2
    s += RC::harness_lua_convert(payload); // VERBATIM extracted statement (f4_statement.inc)
#else
#error "compile with -DHARNESS_CONVERSION=1 (deployed-NUL sim) or =2 (extracted statement)"
#endif
    s += STR("\n");
    return s;
}

static void wide_writer(int n)
{
    for (int i = 0; i < n; ++i)
    {
        RC::Output::send(lua_line(kPayload)); // Writer 1: Output::send(StringType) -> non-template send
    }
}

static void narrow_writer(int n, uint32_t seq_base)
{
    for (int i = 0; i < n; ++i)
    {
        // Writer 2: [l22] template send(StringViewType, FmtArgs...) — the
        // l22-diagnostics drain-loop shape (fmt-formatted narrow args, \n in
        // the format string like the deployed overlay lines).
        RC::Output::send(STR("[l22] ExecuteInGameThread callback returned state=0x8801db3e8 ref=12 seq={}\n"), seq_base + static_cast<uint32_t>(i));
    }
}

static void setup_device(const std::string& path)
{
    auto& device = RC::Output::set_default_devices<RC::Output::NewFileDevice>();
    std::filesystem::path p{path};
    device.set_file_name_and_path(RC::StringType(p.native().begin(), p.native().end())); // profile-agnostic construction (char16_t under the FORCE_U16 host profile)
}

int main(int argc, char** argv)
{
    if (argc < 3)
    {
        std::fprintf(stderr, "usage: %s race|parity <out.log> [n]\n", argv[0]);
        return 2;
    }
    const std::string mode = argv[1];
    const std::string path = argv[2];
    const int n = argc > 3 ? std::atoi(argv[3]) : 400;

    setup_device(path);

    if (mode == "race")
    {
        std::atomic<bool> go{false};
        std::thread w1([&] {
            while (!go) std::this_thread::yield();
            wide_writer(n);
        });
        std::thread w2([&] {
            while (!go) std::this_thread::yield();
            narrow_writer(n * 2, 1000000u);
        });
        go = true;
        w1.join();
        w2.join();
    }
    else if (mode == "parity")
    {
        for (int i = 0; i < n; ++i)
        {
            wide_writer(1);
            narrow_writer(1, 5000000u + static_cast<uint32_t>(i));
        }
    }
    else
    {
        std::fprintf(stderr, "unknown mode %s\n", mode.c_str());
        return 2;
    }

    RC::Output::close_all_default_devices();
    return 0;
}
