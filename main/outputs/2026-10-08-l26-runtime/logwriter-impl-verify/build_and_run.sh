#!/bin/zsh
# build_and_run.sh — logwriter F1-F4 harness build + scenarios + analysis (agent CL)
#
# Builds three binaries from THE REAL staged units (original/ vs candidate/):
#   bin-orig    original F1-F3 units + VERBATIM original conversion statement
#   bin-sim     original F1-F3 units + deployed-codecvt NUL simulation
#   bin-fixed   candidate F1-F3 units + VERBATIM F4 conversion statement
# then runs:
#   1) race scenarios with forced 32-byte short writes -> HARNESS-RUN.txt
#   2) parity scenario (serialized) orig vs fixed, timestamp-normalized byte diff
# All verbatim-extraction and region shas land in EXTRACTION-SHAS.txt.
set -euo pipefail

WHAT=/WORKSPACE/.codex/worktrees/translation-core/what
T4=$WHAT/outputs/2026-10-08-l26-runtime/typescan-r4
VDIR=$WHAT/outputs/2026-10-08-l26-runtime/logwriter-impl-verify
PORT=$WHAT/.superpowers/native-dependency-spike/native-coherent-runtime-1/source/port
DEPS=$WHAT/.superpowers/native-dependency-spike/ue4ss-unreal-native-build-1/source-dependencies/ue4ss/deps/first
FMT=$PORT/fmt/include
VFMT=$WHAT/.superpowers/native-dependency-spike/ue4ss-unreal-native-build-1/source-dependencies/fmt/include

CXX=${CXX:-/usr/bin/clang++}
N=${N:-400}

SHAS=$VDIR/EXTRACTION-SHAS.txt
: > $SHAS
sha_line() { printf '%s  %s\n' "$1" "$2" | tee -a $SHAS }

# ---------------------------------------------------------------------------
# 1) Verbatim extraction of the conversion statements (whole source lines)
# ---------------------------------------------------------------------------
extract_line() { grep -F "$2" "$1" || true; }

ORIG_LUA=$T4/original/src/LuaLibrary.cpp
CAND_LUA=$T4/candidate/src/LuaLibrary.cpp
mkdir -p $VDIR/b-orig $VDIR/b-sim $VDIR/b-fixed $VDIR/out

count_lines() { printf '%s\n' "$1" | grep -c . || true; }
ORIG_STMT=$(extract_line $ORIG_LUA 'auto lua_str = to_generic_string(raw_string);')
CAND_STMT=$(extract_line $CAND_LUA 'auto lua_str = Unicode::DecodeUtf8(std::string_view{raw_string});')
if [[ $(count_lines "$ORIG_STMT") != 1 || $(count_lines "$CAND_STMT") != 1 ]]; then
  echo "FATAL: statement extraction not unique (orig=[$ORIG_STMT] cand=[$CAND_STMT])" >&2; exit 1
fi

make_inc() { # out.inc, statement, source-file, label
  { printf '// GENERATED by build_and_run.sh — VERBATIM whole-line extraction\n'
    printf '// source: %s (%s)\n' "$3" "$4"
    printf '// (wrapped in namespace RC so unqualified names resolve exactly as\n'
    printf '//  they do inside RC::LuaLibrary::global_print)\n'
    printf 'namespace RC {\n'
    printf 'static auto harness_lua_convert(const char* raw_string) -> StringType\n'
    printf '{\n'
    printf '    %s\n' "$2"
    printf '    return lua_str;\n'
    printf '}\n'
    printf '} // namespace RC\n'
  } > "$1"
  printf '%s  %s (whole line)\n' "$(printf '%s\n' "$2" | shasum -a 256 | cut -d' ' -f1)" "$4" | tee -a $SHAS
  printf '%s  %s (generated inc)\n' "$(shasum -a 256 "$1" | cut -d' ' -f1)" "$1" | tee -a $SHAS
}
make_inc $VDIR/b-orig/f4_statement.inc  "$ORIG_STMT" $ORIG_LUA "original LuaLibrary.cpp global_print payload statement"
make_inc $VDIR/b-sim/f4_statement.inc   "$ORIG_STMT" $ORIG_LUA "original LuaLibrary.cpp global_print payload statement (sim binary)"
make_inc $VDIR/b-fixed/f4_statement.inc "$CAND_STMT" $CAND_LUA "candidate LuaLibrary.cpp global_print F4 statement"

# ---------------------------------------------------------------------------
# 2) Region shas of every edited region (F1/F2/F3 compiled directly from the
#    staged files; these receipts document exactly which text is live)
# ---------------------------------------------------------------------------
region_sha() { # file, start-fixed-string, end-fixed-string, label
  local f=$1 start=$2 end=$3 label=$4 sha s e
  s=$(grep -n -F "$start" "$f" | head -1 | cut -d: -f1)
  e=$(grep -n -F "$end" "$f" | awk -v s="$s" -F: '$1 >= s {print $1; exit}')
  if [[ -z "$s" || -z "$e" || $e -lt $s ]]; then
    echo "FATAL: region anchors not found for $label (start=$s end=$e)" >&2; exit 1
  fi
  sha=$(sed -n "${s},${e}p" "$f" | shasum -a 256 | cut -d' ' -f1)
  printf '%s  %s [lines %s-%s] (%s)\n' "$sha" "$label" "$s" "$e" "$f" | tee -a $SHAS
}
region_sha $T4/candidate/include/DynamicOutput/FileDevice.hpp 'auto receive(File::StringViewType fmt) const -> void override' '// OutputDevice Interface -> END' "F1+F3 FileDevice::receive + lock/unlock region"
region_sha $T4/candidate/include/DynamicOutput/FileDevice.hpp 'mutable std::recursive_mutex m_write_mutex;' 'm_write_mutex;' "F1 FileDevice mutex member line"
region_sha $T4/candidate/src/DynamicOutput/Output.cpp 'auto send(File::StringViewType content) -> void' 'close_all_default_devices() -> void' "F2 Output::send body"
region_sha $T4/candidate/src/File/FileType/PosixFile.cpp 'auto encode_utf8_into(StringViewType text' 'auto decode_utf8(const std::vector<uint8_t>& bytes)' "F3 encode_utf8_into region"
region_sha $T4/candidate/src/File/FileType/PosixFile.cpp 'auto PosixFile::write_string_to_file(StringViewType text)' 'auto PosixFile::memory_map()' "F3 write_string_to_file body"

# ---------------------------------------------------------------------------
# 3) Compile the real units (variant include dir FIRST, then port, then deps)
# ---------------------------------------------------------------------------
COMMON_FLAGS=(-std=c++23 -O2 -fPIC
  -DRC_FILE_USE_POSIX_BACKEND -DFMT_HEADER_ONLY -DFORCE_U16
  -DRC_DYNAMIC_OUTPUT_BUILD_STATIC -DRC_FILE_BUILD_STATIC -DRC_HELPERS_BUILD_STATIC
  -Wno-unknown-pragmas -Wno-unused-parameter -Wno-unused-variable
  -include algorithm
  -I $PORT/first/include -I $FMT -I $VFMT
  -I $DEPS/DynamicOutput/include -I $DEPS/File/include -I $DEPS/Helpers/include
  -I $DEPS/String/include -I $DEPS/Constructs/include)
# -DFORCE_U16 (RUNTIME profile): the tree's own 2-byte CharType host profile,
#   required because host libc++ cannot LINK a runnable -fshort-wchar binary
#   (prebuilt wide facets assume 4-byte wchar_t; verified SIGABRT). The target
#   compiler check uses -fshort-wchar in COMPILE-ONLY mode (see
#   compile-matrix.sh), exactly like the l25 combined host smoke.
# -include algorithm: host include-order shim for Helpers/String.hpp's
#   std::count prerequisite (reached via <algorithm> through OutputDevice.hpp
#   in the target composition).

build_variant() { # name staged-rootdir conversion
  local name=$1 root=$2 conv=$3
  local bdir=$VDIR/b-$name
  local incdir=$root/include
  echo "== building $name (units from $root, HARNESS_CONVERSION=$conv)"
  # -I $incdir MUST come before COMMON_FLAGS: COMMON_FLAGS contains
  # port first/include which also has DynamicOutput/FileDevice.hpp — the
  # staged variant copy has to win or the harness silently compiles the
  # unlocked original header.
  $CXX -I $incdir $COMMON_FLAGS -c $root/src/DynamicOutput/Output.cpp  -o $bdir/Output.o
  $CXX -I $incdir $COMMON_FLAGS -c $root/src/File/FileType/PosixFile.cpp -Dwrite=chunked_write -o $bdir/PosixFile.o
  $CXX -I $incdir $COMMON_FLAGS -c $PORT/first/src/DynamicOutput/OutputDevice.cpp -o $bdir/OutputDevice.o
  $CXX -I $incdir $COMMON_FLAGS -c $PORT/first/src/File/File.cpp -o $bdir/File.o
  $CXX -I $incdir $COMMON_FLAGS -c $VDIR/time_shim.cpp -o $bdir/Time.o
  $CXX -I $incdir $COMMON_FLAGS -I $bdir -DHARNESS_CONVERSION=$conv -c $VDIR/harness_main.cpp -o $bdir/harness_main.o
  # include-resolution proof: which FileDevice.hpp did the harness TU use?
  $CXX -I $incdir $COMMON_FLAGS -I $bdir -DHARNESS_CONVERSION=$conv -fsyntax-only -H $VDIR/harness_main.cpp 2>&1 | grep -F 'FileDevice.hpp' | tee -a $SHAS
  $CXX $bdir/harness_main.o $bdir/Output.o $bdir/PosixFile.o $bdir/OutputDevice.o $bdir/File.o $bdir/Time.o -o $VDIR/bin-$name
}

build_variant orig  $T4/original 2
build_variant sim   $T4/original 1
build_variant fixed $T4/candidate 2

# ---------------------------------------------------------------------------
# 4) Scenarios
# ---------------------------------------------------------------------------
echo "== race scenarios (two threads, forced 32-byte short writes, N=$N)"
$VDIR/bin-sim   race $VDIR/out/1-sim-deployed-nul.log   $N
$VDIR/bin-orig  race $VDIR/out/2-orig-race.log          $N
$VDIR/bin-fixed race $VDIR/out/3-fixed-race.log         $N
echo "== parity scenario (serialized alternating)"
$VDIR/bin-orig  parity $VDIR/out/parity-orig.log  120
$VDIR/bin-fixed parity $VDIR/out/parity-fixed.log 120

# ---------------------------------------------------------------------------
# 5) Analysis -> HARNESS-RUN.txt
# ---------------------------------------------------------------------------
python3 - "$VDIR" "$N" <<'EOF' | tee $VDIR/HARNESS-RUN.txt
import re, sys
from pathlib import Path
vdir=Path(sys.argv[1]); N=int(sys.argv[2])
line_re=re.compile(rb'^\[\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}\] \[(Lua|l22)\] ')
tail=b"in method 'GetItemIDFromDeprecatedEnum'"
def analyze(p):
    data=Path(p).read_bytes()
    lines=data.split(b'\n')
    lines=[l for l in lines if l]
    bad=0; first=None
    for l in lines:
        if not line_re.match(l) or b'\x00' in l:
            bad+=1
            if first is None: first=l[:100]
    lua=sum(1 for l in lines if line_re.match(l) and line_re.match(l).group(1)==b'Lua')
    l22=sum(1 for l in lines if line_re.match(l) and line_re.match(l).group(1)==b'l22')
    tails=sum(1 for l in lines if tail in l)
    nul=data.count(b'\x00')
    return bad,lua,l22,tails,nul,first
print("logwriter F1-F4 harness (REAL staged units, 32B short writes, two threads)")
for name,exp_lua,exp_l22 in [("1-sim-deployed-nul.log",N,2*N),("2-orig-race.log",N,2*N),("3-fixed-race.log",N,2*N)]:
    bad,lua,l22,tails,nul,first=analyze(vdir/'out'/name)
    print(f"{name:26s} corrupted={bad:4d} lua={lua:4d}/{exp_lua} l22={l22:4d}/{exp_l22} full-tails={tails:4d}/{exp_lua} NUL-bytes={nul}")
    if first: print(f"   first bad: {first!r}")
# parity
def norm(p):
    return re.sub(rb'\[\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}\]', b'[TS]', Path(p).read_bytes())
a=norm(vdir/'out/parity-orig.log'); b=norm(vdir/'out/parity-fixed.log')
print(f"parity (serialized, timestamps normalized): {'IDENTICAL' if a==b else 'DIFFER'} ({len(a)} vs {len(b)} bytes)")
ok = True
for name in ("3-fixed-race.log",):
    bad,lua,l22,tails,nul,_=analyze(vdir/'out'/name)
    ok = ok and bad==0 and lua==N and l22==2*N and tails==N and nul==0
sim_bad=analyze(vdir/'out/1-sim-deployed-nul.log')[0]
orig_bad=analyze(vdir/'out/2-orig-race.log')[0]
print(f"VERDICT: deployed-sim corrupts ({sim_bad}), original-code race corrupts ({orig_bad}), fixed = zero corruption + zero NULs ({'PASS' if ok and sim_bad>0 and orig_bad>0 else 'FAIL'}); parity {a==b}")
EOF
