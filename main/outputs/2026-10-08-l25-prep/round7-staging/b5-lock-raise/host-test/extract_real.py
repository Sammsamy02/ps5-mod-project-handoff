#!/usr/bin/env python3
"""Extracts the REAL B2 error-wrapper code out of the candidate tree (read-only)
into real_pieces.inc, byte for byte, with ONE documented adaptation
(fmt::format -> std::string concat, because the host test does not link fmt).
Prints how many pieces / lines it extracted; exits non-zero if any anchor is
missing or the count is zero."""
import hashlib, re, sys

CAND = "/WORKSPACE/.codex/worktrees/translation-core/what/outputs/2026-10-08-l26-runtime/typescan-r4/candidate"
CPP = CAND + "/src/LuaMadeSimple/LuaMadeSimple.cpp"
HPP = CAND + "/include/LuaMadeSimple/LuaMadeSimple.hpp"

def load(p):
    raw = open(p, "rb").read()
    return hashlib.sha256(raw).hexdigest(), raw.decode("utf-8").split("\n")

def span(lines, start_re, end_re, label):
    s = next((i for i, l in enumerate(lines) if re.search(start_re, l)), None)
    if s is None:
        sys.exit("FAIL: start anchor not found for " + label)
    e = next((i for i in range(s, len(lines)) if re.search(end_re, lines[i])), None)
    if e is None:
        sys.exit("FAIL: end anchor not found for " + label)
    return s, e

cpp_sha, cpp = load(CPP)
hpp_sha, hpp = load(HPP)
pieces = []  # (label, file, first_line_1based, last_line_1based, text)

def add(label, fname, lines, start_re, end_re, extra_after_end=0):
    s, e = span(lines, start_re, end_re, label)
    e += extra_after_end
    pieces.append((label, fname, s + 1, e + 1, "\n".join(lines[s:e + 1])))

# P1 counter struct
s, e = span(cpp, r"struct LmsRelaxedCounter", r"^    \};$", "P1")
pieces.append(("P1 LmsRelaxedCounter", "LuaMadeSimple.cpp", s + 1, e + 1, "\n".join(cpp[s:e + 1])))
# P2 observability globals, copy_text_bounded, capture_cxx_exception_text, copy_last_raised_error
s, _ = span(cpp, r"\[B2\] error-wrapper observability", r".", "P2s")
_, e = span(cpp, r"copy_text_bounded\(out, out_size, g_last_raised_error\);", r"^    \}$", "P2e")
e = next(i for i in range(e, len(cpp)) if re.match(r"^    \}$", cpp[i]))
pieces.append(("P2 globals/copy_text_bounded/capture/copy_last", "LuaMadeSimple.cpp", s + 1, e + 1, "\n".join(cpp[s:e + 1])))
# P3 handle_error .. throw_error_from_buffer
s, _ = span(cpp, r"auto RC_LMS_API handle_error\(lua_State\* lua_state", r".", "P3s")
_, e = span(cpp, r"auto throw_error_from_buffer\(lua_State\* lua_state, const char\* message\)", r"^    \}$", "P3e")
e = next(i for i in range(e, len(cpp)) if re.match(r"^    \}$", cpp[i]))
pieces.append(("P3 handle_error/throw_error_impl/throw_error/throw_error_from_buffer", "LuaMadeSimple.cpp", s + 1, e + 1, "\n".join(cpp[s:e + 1])))
# P4 TRY (hpp)
s, _ = span(hpp, r"template <typename CodeToTry>", r".", "P4s")
# the free-function TRY is the one taking lua_State*
s = next(i for i, l in enumerate(hpp) if re.search(r"auto constexpr TRY\(lua_State\* lua_state, CodeToTry code_to_try\) -> int", l)) - 1
e = next(i for i in range(s, len(hpp)) if re.match(r"^    \}$", hpp[i]))
pieces.append(("P4 free TRY(lua_State*, ...)", "LuaMadeSimple.hpp", s + 1, e + 1, "\n".join(hpp[s:e + 1])))

if not pieces or sum(len(p[4]) for p in pieces) == 0:
    sys.exit("FAIL: extracted zero pieces")

ADAPT_FROM = 'fmt::format("{}\\nNo traceback", error_message)'
ADAPT_TO = 'error_message + "\\nNo traceback"'

out = ["// GENERATED by extract_real.py -- do not edit.",
       "// Source (read-only): " + CPP + " sha256 " + cpp_sha,
       "//                    " + HPP + " sha256 " + hpp_sha,
       "// Byte-for-byte copies except ONE adaptation: " + ADAPT_FROM + " -> " + ADAPT_TO,
       "// (host test does not link fmt).", ""]
adapted = 0
total_lines = 0
for label, f, a, b, text in pieces:
    if ADAPT_FROM in text:
        text = text.replace(ADAPT_FROM, ADAPT_TO)
        adapted += 1
    out.append("// ---- %s  [%s:%d-%d] ----" % (label, f, a, b))
    out.append(text)
    out.append("")
    total_lines += b - a + 1
    print("extracted %-70s %s:%d-%d" % (label, f, a, b))
if adapted != 1:
    sys.exit("FAIL: expected exactly 1 adaptation site, got %d" % adapted)
open("real_pieces.inc", "w").write("\n".join(out) + "\n")
print("checked: %d pieces, %d source lines, %d adaptation(s); cpp sha %s hpp sha %s" % (len(pieces), total_lines, adapted, cpp_sha[:8], hpp_sha[:8]))
