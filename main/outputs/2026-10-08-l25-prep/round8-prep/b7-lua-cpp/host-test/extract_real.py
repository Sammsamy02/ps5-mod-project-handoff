#!/usr/bin/env python3
"""Extracts the REAL runtime code the B7 host test exercises, byte for byte (read-only), into
generated .inc files next to this script:

  real_cur.inc        B2 wrapper as it is TODAY (candidate LuaMadeSimple.cpp, unpatched)
  real_fixed.inc      same pieces from the STAGED B7 file (staged-patch/b7-on-candidate/tree)
  real_try.inc        free TRY(lua_State*, ...) template (candidate LuaMadeSimple.hpp)
  real_uobj_cur.inc   protected_ufunction_call + call_ufunction_from_lua, candidate LuaUObject.cpp
  real_uobj_fixed.inc same, staged B7 file
  real_probe.inc      the [B7-PROBE-BEGIN..END] block of the staged LuaMadeSimple.cpp

ONE documented adaptation (host test does not link fmt):
  fmt::format("{}\\nNo traceback", error_message) -> error_message + "\\nNo traceback"
Prints each piece with source line numbers and the source shas. Exits non-zero if an anchor is
missing, a count is wrong, or nothing was extracted.
"""
import hashlib, re, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
WHAT = HERE.parents[4]
CAND = WHAT / 'outputs/2026-10-08-l26-runtime/typescan-r4/candidate'
STAGED = HERE.parent / 'staged-patch/b7-on-candidate/tree/outputs/2026-10-08-l26-runtime/typescan-r4/candidate'

ADAPT_FROM = 'fmt::format("{}\\nNo traceback", error_message)'
ADAPT_TO = 'error_message + "\\nNo traceback"'


def load(p):
    raw = p.read_bytes()
    return hashlib.sha256(raw).hexdigest(), raw.decode('utf-8').split('\n')


def find(lines, pat, start=0, label=''):
    for i in range(start, len(lines)):
        if re.search(pat, lines[i]): return i
    sys.exit(f'FAIL: anchor not found: {label or pat}')


def end_of_block(lines, i, indent):
    """first line >= i that is exactly '<indent>}' (closing brace at the given indent)."""
    for j in range(i, len(lines)):
        if lines[j] == indent + '}': return j
    sys.exit(f'FAIL: no closing brace at indent {len(indent)} after line {i + 1}')


def pieces_lms(cpp):
    out = []
    s = find(cpp, r'struct LmsRelaxedCounter')
    out.append(('P1 LmsRelaxedCounter', s, end_of_block(cpp, s, '    ') if False else next(j for j in range(s, len(cpp)) if cpp[j] == '    };')))
    s = find(cpp, r'\[B2\] error-wrapper observability')
    e = find(cpp, r'copy_text_bounded\(out, out_size, g_last_raised_error\);')
    e = end_of_block(cpp, e, '    ')
    out.append(('P2 globals/copy_text_bounded/capture/copy_last', s, e))
    s = find(cpp, r'auto RC_LMS_API handle_error\(lua_State\* lua_state')
    e = find(cpp, r'auto throw_error_from_buffer\(lua_State\* lua_state, const char\* message\)')
    e = end_of_block(cpp, e, '    ')
    out.append(('P3 handle_error/throw_error_impl/throw_error/throw_error_from_buffer', s, e))
    return out


def pieces_uobj(cpp):
    out = []
    s = find(cpp, r'static auto protected_ufunction_call\(lua_State\* LuaState\) -> int')
    out.append(('U1 protected_ufunction_call', s, end_of_block(cpp, s, '    ')))
    # the __PROSPERO__ variant: the one whose body declares FNativeUFunctionCall (the other is the
    # non-PROSPERO definition behind #else)
    k = find(cpp, r'FNativeUFunctionCall Invocation\{lua\};')
    s = max(i for i in range(k) if re.search(r'auto call_ufunction_from_lua\(const LuaMadeSimple::Lua& lua\) -> int', cpp[i]))
    out.append(('U2 call_ufunction_from_lua (PROSPERO variant)', s, end_of_block(cpp, s, '    ')))
    return out


def emit(path, header, src_path, sha, lines, spans, adapt):
    buf = [f'// GENERATED by extract_real.py -- do not edit.', f'// {header}', f'// Source (read-only): {src_path.relative_to(WHAT)} sha256 {sha}']
    if adapt: buf.append(f'// Byte-for-byte copies except ONE adaptation: {ADAPT_FROM} -> {ADAPT_TO}')
    buf.append('')
    n_adapt = n_lines = 0
    for label, s, e in spans:
        text = '\n'.join(lines[s:e + 1])
        if ADAPT_FROM in text:
            text = text.replace(ADAPT_FROM, ADAPT_TO); n_adapt += 1
        buf.append(f'// ---- {label}  [{src_path.name}:{s + 1}-{e + 1}] ----')
        buf.append(text); buf.append('')
        n_lines += e - s + 1
        print(f'  {path.name:20s} {label:70s} {src_path.name}:{s + 1}-{e + 1}')
    path.write_text('\n'.join(buf) + '\n')
    return n_adapt, n_lines


def main():
    total_lines = 0
    cand_sha, cand = load(CAND / 'src/LuaMadeSimple/LuaMadeSimple.cpp')
    stg_sha, stg = load(STAGED / 'src/LuaMadeSimple/LuaMadeSimple.cpp')
    hpp_sha, hpp = load(CAND / 'include/LuaMadeSimple/LuaMadeSimple.hpp')
    uo_sha, uo = load(CAND / 'src/LuaUObject.cpp')
    uos_sha, uos = load(STAGED / 'src/LuaUObject.cpp')
    a1, n1 = emit(HERE / 'real_cur.inc', 'B2 wrapper as it is today (B4 candidate)', CAND / 'src/LuaMadeSimple/LuaMadeSimple.cpp', cand_sha, cand, pieces_lms(cand), True)
    a2, n2 = emit(HERE / 'real_fixed.inc', 'B2 wrapper with the staged B7 edit (E2)', STAGED / 'src/LuaMadeSimple/LuaMadeSimple.cpp', stg_sha, stg, pieces_lms(stg), True)
    if a1 != 1 or a2 != 1: sys.exit(f'FAIL: expected exactly 1 adaptation per file, got {a1}/{a2}')
    s = next(i for i, l in enumerate(hpp) if re.search(r'auto constexpr TRY\(lua_State\* lua_state, CodeToTry code_to_try\) -> int', l)) - 1
    e = next(i for i in range(s, len(hpp)) if hpp[i] == '    }')
    n3 = emit(HERE / 'real_try.inc', 'free TRY(lua_State*, ...) template', CAND / 'include/LuaMadeSimple/LuaMadeSimple.hpp', hpp_sha, hpp, [('T1 free TRY', s, e)], False)[1]
    n4 = emit(HERE / 'real_uobj_cur.inc', 'LuaUObject.cpp as it is today', CAND / 'src/LuaUObject.cpp', uo_sha, uo, pieces_uobj(uo), False)[1]
    n5 = emit(HERE / 'real_uobj_fixed.inc', 'LuaUObject.cpp with the staged B7 edit (E1)', STAGED / 'src/LuaUObject.cpp', uos_sha, uos, pieces_uobj(uos), False)[1]
    s = find(stg, r'\[B7-PROBE-BEGIN\]'); e = find(stg, r'\[B7-PROBE-END\]', s)
    n6 = emit(HERE / 'real_probe.inc', 'startup probe block (staged P1)', STAGED / 'src/LuaMadeSimple/LuaMadeSimple.cpp', stg_sha, stg, [('B7 probe', s, e)], False)[1]
    total_lines = n1 + n2 + n3 + n4 + n5 + n6
    # sanity: the fixed copy must differ from the current copy exactly by the pass-through handler
    cur = (HERE / 'real_uobj_cur.inc').read_text(); fix = (HERE / 'real_uobj_fixed.inc').read_text()
    if 'catch (void*)' in cur or 'catch (void*)' not in fix: sys.exit('FAIL: E1 not present only in the fixed copy')
    cur = (HERE / 'real_cur.inc').read_text(); fix = (HERE / 'real_fixed.inc').read_text()
    if 'catch (void*)' in cur or 'catch (void*)' not in fix: sys.exit('FAIL: E2 not present only in the fixed copy')
    if total_lines == 0: sys.exit('FAIL: extracted zero lines')
    print(f'checked: 6 files, {total_lines} source lines; shas cur-cpp {cand_sha[:8]} staged-cpp {stg_sha[:8]} hpp {hpp_sha[:8]} uobj {uo_sha[:8]} staged-uobj {uos_sha[:8]}')


if __name__ == '__main__':
    main()
