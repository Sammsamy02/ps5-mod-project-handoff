#!/usr/bin/env python3
"""Stage launch 2 (B5 or B6): Mac-only, NO console contact.

Starts from the loadlist + pins that are on the console now (morning deploy,
row-check 30/30 PASS at 11:55Z) and changes only:
  - InfiniteStamina rows removed (does nothing on PC either; reviewer item 5)
  - SpeedHackMod rows added (Nexus mod 10, original download, unmodified)
  - ue4ss/PS5Pad.ini regenerated by keymap-gen.py (adds SpeedHack F1-F4 combos)
  - zzdiag (ours) v11 -> v12 (dispatch probe; fixes v11's 'ts' error)
  - optional: --selftest-dir DIR replaces the self-test scripts (B6 GAPS fix)

Writes loadlist.txt, rowcheck-pins.json, upload/ (exactly the files that change),
fixture/ (full local mirror of the console root for an offline row-check) and
STAGE-RECEIPT.json. Exit 1 on any problem or zero rows.
"""
import argparse, hashlib, json, os, shutil, subprocess, sys, time

HERE = os.path.dirname(os.path.abspath(__file__))
P = os.path.dirname(HERE)
CUR = P + '/morning-launch-20261012'
SPOOL = P + '/evidence/morning-readonly-20261012T114008Z/spool/rows'   # console copies, 11:40Z
SH = P + '/mod-intake-20261012/SpeedHack-nexus10/extracted/SpeedHackMod/Scripts/main.lua'
SH_SHA = 'd0d2b85e100d944258e246bb6e924fab507dcdcd2aa7730651fea06a690d6c0d'
PAD = P + '/mod-intake-20261012/PS5Pad.speedhack.ini'
ZZ = P + '/evidence/launch-l26-B4-launch1-20261012/analysis/spawner-menu/proposed-zzdiag-v12/main.lua'
EMPTY = hashlib.sha256(b'').hexdigest()


def sha(p):
    return hashlib.sha256(open(p, 'rb').read()).hexdigest()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--selftest-dir', default=None, help='replacement ueselftest/Scripts dir (B6)')
    a = ap.parse_args()
    if sha(SH) != SH_SHA:
        print('FAIL: SpeedHack main.lua is not the original download'); return 1
    for f in (ZZ, PAD) + ((SH,)):
        r = subprocess.run(['luac', '-p', f], capture_output=True, text=True) if f.endswith('.lua') else None
        if r is not None and r.returncode != 0:
            print('FAIL: Lua syntax check: ' + r.stderr.strip()); return 1
    pins = json.load(open(CUR + '/rowcheck-pins.json'))
    header, rows = [], []
    for ln in open(CUR + '/loadlist.txt').read().splitlines():
        parts = ln.split('\t')
        (rows if parts[0] == 'file' else header).append(parts)
    src = {}       # row path -> local file with the exact bytes the console must have
    for r in rows:
        src[r[2]] = None if r[2].endswith('enabled.txt') else SPOOL + '/' + r[2]
    for r in rows:  # self-test copies come from the morning upload set
        if r[2].startswith('ue4ss/Mods/ueselftest/Scripts/'):
            src[r[2]] = CUR + '/upload/' + r[2]
    rows = [r for r in rows if not r[2].startswith('ue4ss/Mods/InfiniteStamina/')]
    rows += [['file', 'lua_mod', 'ue4ss/Mods/SpeedHackMod/Scripts/main.lua', '0'],
             ['file', 'config', 'ue4ss/Mods/SpeedHackMod/enabled.txt', '0']]
    src['ue4ss/Mods/SpeedHackMod/Scripts/main.lua'] = SH
    src['ue4ss/Mods/SpeedHackMod/enabled.txt'] = None
    src['ue4ss/PS5Pad.ini'] = PAD
    src['ue4ss/Mods/zzdiag/Scripts/main.lua'] = ZZ
    if a.selftest_dir:
        for r in rows:
            if r[2].startswith('ue4ss/Mods/ueselftest/Scripts/'):
                src[r[2]] = os.path.join(a.selftest_dir, os.path.basename(r[2]))
    new_pins, upload, problems = {}, [], []
    for r in rows:
        path, f = r[2], src.get(r[2])
        if f is None:
            size, digest = 0, EMPTY
        elif not os.path.isfile(f):
            problems.append('no local source: ' + path); continue
        else:
            size, digest = os.path.getsize(f), sha(f)
        old = pins.get(path)
        unchanged = old is not None and old['size'] == size and old['sha256'] == digest
        if old is not None and f is not None and f.startswith(SPOOL) and not unchanged:
            problems.append('console copy differs from its pin: ' + path)
        r[3] = str(size)
        new_pins[path] = {'size': size, 'sha256': digest}
        if not unchanged:
            upload.append((path, f))
    if problems or not rows:
        print('STAGING FAIL:', *problems or ['zero rows'], sep='\n  '); return 1
    text = '\n'.join('\t'.join(h) for h in header) + '\n' + '\n'.join('\t'.join(r) for r in rows) + '\n'
    for d in ('upload', 'fixture'):
        shutil.rmtree(HERE + '/' + d, ignore_errors=True)
    os.makedirs(HERE + '/upload', exist_ok=True)
    open(HERE + '/loadlist.txt', 'w').write(text)
    shutil.copyfile(HERE + '/loadlist.txt', HERE + '/upload/loadlist.txt')
    for path, f in upload:
        os.makedirs(os.path.dirname(HERE + '/upload/' + path), exist_ok=True)
        if f is None:
            open(HERE + '/upload/' + path, 'wb').close()
        else:
            shutil.copyfile(f, HERE + '/upload/' + path)
    os.makedirs(HERE + '/fixture', exist_ok=True)   # full console-root mirror for the offline row-check
    shutil.copyfile(HERE + '/loadlist.txt', HERE + '/fixture/loadlist.txt')
    for r in rows:
        dst = HERE + '/fixture/' + r[2]
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        if src[r[2]] is None:
            open(dst, 'wb').close()
        else:
            shutil.copyfile(src[r[2]], dst)
    new_pins['loadlist.txt'] = {'size': len(text.encode()), 'sha256': hashlib.sha256(text.encode()).hexdigest()}
    json.dump(new_pins, open(HERE + '/rowcheck-pins.json', 'w'), indent=1, sort_keys=True)
    rec = {'staged_utc': time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime()), 'console_contact': False,
           'rows': len(rows), 'upload': [p for p, _ in upload] + ['loadlist.txt'],
           'loadlist_sha256': new_pins['loadlist.txt']['sha256'], 'loadlist_bytes': new_pins['loadlist.txt']['size'],
           'selftest_dir': a.selftest_dir}
    json.dump(rec, open(HERE + '/STAGE-RECEIPT.json', 'w'), indent=1)
    print('STAGED: %d rows; upload %d files + loadlist (%d B, sha %s)' % (
        len(rows), len(upload), rec['loadlist_bytes'], rec['loadlist_sha256'][:16]))
    for p, _ in upload:
        print('  upload ' + p)
    return 0


if __name__ == '__main__':
    sys.exit(main())
