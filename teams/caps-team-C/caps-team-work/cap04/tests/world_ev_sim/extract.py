#!/usr/bin/env python3
"""Extract the SHIPPING code under test, verbatim, from a (patched) runtime tree:

  LuaMod.cpp        : struct R9Pacer .. s_r9_pace_* statics, namespace world_ev, r9_feed_notify_from_index
  UObjectGlobals.cpp: r9_index_snapshot_live

into <out>/world_ev_extract.inc and <out>/snapshot_extract.inc. The host simulation compiles these
against small stubs (stubs.hpp). Every block must be found exactly once; prints how many blocks it
extracted and fails when any is missing (zero = failure)."""
import sys
from pathlib import Path


def block(text, start, end, include_end=True, name=''):
    i = text.find(start)
    if i < 0 or text.find(start, i + 1) >= 0:
        raise SystemExit('extract: start anchor for %s found %d times' % (name, text.count(start)))
    j = text.find(end, i)
    if j < 0:
        raise SystemExit('extract: end anchor for %s missing' % name)
    return text[i:j + (len(end) if include_end else 0)]


def main():
    tree, out = Path(sys.argv[1]), Path(sys.argv[2])
    out.mkdir(parents=True, exist_ok=True)
    lua = (tree / 'src/LuaMod.cpp').read_text()
    uog = (tree / 'src/UObjectGlobals.cpp').read_text()
    n = 0
    pacer = block(lua, '    struct R9Pacer\n', 'static R9Pacer s_r9_pace_watch{}, s_r9_pace_match{}, s_r9_pace_exec{};', name='R9Pacer'); n += 1
    wev = block(lua, '    namespace world_ev\n', '    } // namespace world_ev\n', name='world_ev'); n += 1
    feed = block(lua, '    static auto r9_feed_notify_from_index() -> void\n', '    static auto process_pending_notify_on_new_object_callbacks() -> void', include_end=False, name='feed'); n += 1
    snap = block(uog, '    auto r9_index_snapshot_live(', '    // [R9-NOTIFY] no registrations left: stop collecting.', include_end=False, name='snapshot'); n += 1
    (out / 'world_ev_extract.inc').write_text('// GENERATED by extract.py from %s -- do not edit\n%s\n%s\n%s\n' % (tree, pacer, wev, feed))
    (out / 'snapshot_extract.inc').write_text('// GENERATED by extract.py from %s -- do not edit\n%s\n' % (tree, snap))
    print('extracted %d blocks (world_ev %d lines, feed %d lines, snapshot %d lines)' % (n, wev.count('\n'), feed.count('\n'), snap.count('\n')))
    if n != 4:
        raise SystemExit(1)


if __name__ == '__main__':
    main()
