#ifndef CAP03_NEAR_TRAMPOLINE_HPP
#define CAP03_NEAR_TRAMPOLINE_HPP

#include "DetourPlan.hpp"

#include <cstddef>
#include <cstdint>

namespace cap03 {

// The backend must reserve a fresh writable mapping without replacing any
// existing mapping. Seal must make the range executable without leaving it
// writable, and release must be safe for every returned mapping. Callbacks
// must not throw and a failed reservation must leave no mapping allocated.
struct NearMemoryOps {
    void* user = nullptr;
    bool (*reserve_writable)(void* user, uint64_t hint, size_t bytes,
                             void** mapping) = nullptr;
    bool (*seal_executable)(void* user, void* mapping, size_t bytes) = nullptr;
    void (*release)(void* user, void* mapping, size_t bytes) = nullptr;
};

enum class NearPrepareStatus {
    Ok,
    BadArgs,
    MappingUnavailable,
    PlanRejected,
    SealFailed
};

struct NearPrepareResult {
    NearPrepareStatus status = NearPrepareStatus::BadArgs;
    DetourPlanResult plan_status = DetourPlanResult::BadArgs;
    size_t candidates_checked = 0;
};

struct PreparedNearDetour {
    DetourPlan plan{};
    void* trampoline = nullptr;
    size_t mapping_bytes = 0;
    NearMemoryOps memory{};
    PreparedNearDetour() = default;
    ~PreparedNearDetour() { reset(); }
    PreparedNearDetour(const PreparedNearDetour&) = delete;
    PreparedNearDetour& operator=(const PreparedNearDetour&) = delete;
    void reset() noexcept;
};

// Reserves a trampoline within the conservative signed-disp32 window of the
// target, runs the full relocation planner at its actual address, copies the
// generated bytes, and seals the mapping RX. Never writes the target. The
// caller must still quiesce threads and use checked patch/restore separately.
NearPrepareResult prepare_near_detour(const uint8_t* original, size_t available,
                                      uint64_t target_address,
                                      uint64_t handler_address,
                                      size_t page_size, NearMemoryOps ops,
                                      PreparedNearDetour* out);

// POSIX/PS5 backend using non-fixed mmap hints and mprotect. Never uses
// MAP_FIXED or overwrites another mapping. The caller passes actual page size.
NearMemoryOps posix_near_memory_ops() noexcept;

} // namespace cap03
#endif
